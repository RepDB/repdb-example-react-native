// Regenerate lib/images.ts from assets/images/flat/*.webp.
// React Native bundles static assets at build time, so each image needs an
// explicit `require()` call. After syncing the preview bundle, run:
//
//   npm run gen-images
//
// Commit the resulting lib/images.ts.

const { readdirSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');

const ROOT = join(__dirname, '..');
const FLAT_DIR = join(ROOT, 'assets/images/flat');
const OUT = join(ROOT, 'lib/images.ts');

const files = readdirSync(FLAT_DIR)
  .filter((f) => f.endsWith('.webp'))
  .sort();

const lines = files.map((f) => {
  const key = f.replace(/\.webp$/, '');
  return `  '${key}': require('../assets/images/flat/${f}'),`;
});

const out = `// Auto-generated by scripts/gen-images.cjs. Do not edit by hand —
// run \`npm run gen-images\` after syncing the bundle.
//
// React Native's Metro bundler resolves \`require()\` of static assets at
// build time only. We map slug-variant -> module ID so other code can do
// \`getImage('arnold-press', 'peak')\` without dynamic require.

export const IMAGES: Record<string, number> = {
${lines.join('\n')}
};

export type ImageVariant = 'start' | 'peak';

export function getImage(slug: string, variant: ImageVariant): number | undefined {
  return IMAGES[\`\${slug}-\${variant}\`];
}
`;

writeFileSync(OUT, out);
console.log(`Generated ${files.length} entries -> lib/images.ts`);
